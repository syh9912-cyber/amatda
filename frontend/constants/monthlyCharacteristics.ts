/**
 * 주어진 월령에 해당하는 발달 특성을 반환합니다.
 */
export function getCharacteristicForMonth(month: number): MonthlyCharacteristic | null {
  if (month < 1 || month > 144) {
    return null;
  }

  // 1~72개월: 월별 데이터
  if (month <= 72) {
    return MONTHLY_CHARACTERISTICS.find((c) => c.month === month && !c.endMonth) ?? null;
  }

  // 73~144개월: 학년별 데이터 (범위 매칭)
  return (
    MONTHLY_CHARACTERISTICS.find(
      (c) => c.endMonth !== undefined && month >= c.month && month <= c.endMonth
    ) ?? null
  );
}

/**
 * 월령과 기질 유형에 맞는 발달 특성과 기질별 맞춤 팁을 반환합니다.
 */
export function getCharacteristicForChild(
  ageMonths: number,
  temperament: string
): { characteristic: MonthlyCharacteristic; temperamentTip: string } | null {
  const characteristic = getCharacteristicForMonth(ageMonths);
  if (!characteristic) {
    return null;
  }

  const temperamentTip =
    characteristic.temperamentTips[temperament] ??
    characteristic.temperamentTips['조화형'] ??
    '';

  return {
    characteristic,
    temperamentTip,
  };
}
