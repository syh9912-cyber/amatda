export type AgeGroup = 'infant' | 'kinder' | 'elem_low' | 'elem_high';

export function getAgeGroup(months: number): AgeGroup {
  if (months <= 36) return 'infant';
  if (months <= 72) return 'kinder';
  if (months <= 108) return 'elem_low';
  return 'elem_high';
}

