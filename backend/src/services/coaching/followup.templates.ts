/**
 * AI 팔로업이 3개 미만이면 카테고리 템플릿으로 채워 정확히 3개로 맞춘다 (중복 제거).
 * @param existing AI 생성 + 인터뷰식 필터 통과한 질문들
 * @param categoryKo 한국어 카테고리 라벨 (예: '수면', '식사', '임신 증상') — 로케일과 무관하게 항상 한국어
 * @param locale 비한국어 로케일이면 번역된 템플릿 풀 사용 (추가형)
 */
export function backfillFollowups(existing: string[], categoryKo: string, locale?: string): string[] {
  const out = existing.filter((q) => typeof q === 'string' && q.trim().length > 0);
  if (out.length >= 3) return out.slice(0, 3);
  const templates = locale === 'ja' ? FOLLOWUP_TEMPLATES_JA : locale === 'zh-Hant' ? FOLLOWUP_TEMPLATES_ZH : FOLLOWUP_TEMPLATES;
  const pool = templates[categoryKo] ?? templates._default;
  for (const q of pool) {
    if (out.length >= 3) break;
    if (!out.includes(q)) out.push(q);
  }
  return out.slice(0, 3);
}
