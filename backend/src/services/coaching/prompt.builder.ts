// ─── Runtime Prompt 빌더 ───

export function buildPrompt(ctx: PromptContext): {
  systemPrompt: string;
  runtimePrompt: string;
} {
  const dbSection = ctx.dbCandidates.length > 0
    ? ctx.dbCandidates.map((c, i) => `${i + 1}. ${c}`).join('\n')
    : '(매칭되는 DB 참고자료 없음)';

  const crySection = ctx.cryAnalysisInput || '없음';
  const poopSection = ctx.poopAnalysisInput || '없음';

  const runtimePrompt = `현재 상담 카테고리: ${ctx.category}

사용자 현재 질문:
${ctx.userMessage}

아이 기본 정보:
- 이름: ${ctx.childName}
- 월령/나이: ${ctx.ageInfo}
- 성별: ${ctx.gender}
- 기질: ${ctx.temperament}
- 특이사항: ${ctx.specialNotes || '없음'}

최근 기록 요약:
- 수면: ${ctx.sleepSummary}
- 식사: ${ctx.mealSummary}
- 대변: ${ctx.poopSummary}
- 체온/컨디션: ${ctx.conditionSummary}
- 최근 변화: ${ctx.recentChangeSummary}

이전 대화 축약:
${ctx.conversationSummary || '(첫 대화)'}

최근 대화 원문:
${ctx.recentChatTurns || '(이전 대화 없음)'}

내부 DB 참고 후보:
${dbSection}

추가 입력:
- 울음소리 분석 정보: ${crySection}
- 대변 색/사진 분석 정보: ${poopSection}

중요 규칙:
- 현재 카테고리와 현재 질문에만 집중해서 답하라.
- 이전 대화는 짧게만 이어받고, 장황하게 반복하지 마라.
- DB 후보는 참고만 하고 복붙하지 마라.
- 답변 첫 문장에서 아이의 기질/성향을 자연스럽게 언급하며 시작하라.
- 입력 정보가 부족하면 꼭 필요한 정보만 1~2개 물어라.
- 반드시 JSON 형식으로만 응답하라.`;

  return { systemPrompt: SYSTEM_PROMPT, runtimePrompt };
}
