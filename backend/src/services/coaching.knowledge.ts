/** 키워드 매칭으로 코칭 엔트리 검색 */
export function findCoachingEntry(message: string): CoachingEntry | null {
  let bestMatch: CoachingEntry | null = null;
  let bestScore = 0;

  for (const entry of COACHING_KNOWLEDGE) {
    let score = 0;
    for (const keyword of entry.keywords) {
      if (message.includes(keyword)) {
        score += keyword.length;
      }
    }
    if (score > bestScore) {
      bestScore = score;
      bestMatch = entry;
    }
  }

  return bestScore > 0 ? bestMatch : null;
}

/** 카테고리별 엔트리 조회 */
export function getEntriesByCategory(category: string): CoachingEntry[] {
  return COACHING_KNOWLEDGE.filter((e) => e.category === category);
}
